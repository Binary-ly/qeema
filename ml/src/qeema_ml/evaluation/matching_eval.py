"""Evaluation harness for product matching.

Publishing an accuracy figure is the point. A matcher whose quality is
unmeasured is a matcher nobody should trust with a published index, and
"it seemed to work in testing" is not a number anyone can act on.

The labelled set is generated by perturbing known variants in the ways
reporters actually make mistakes — dropped hamza, Arabic-Indic digits, typos,
head-noun-only queries, cross-language names. That is a weaker guarantee than
real labelled submissions and this module says so in its own output rather than
letting the reader assume otherwise.

Run: ``python -m qeema_ml.evaluation.matching_eval --catalogue <file.json>``
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

from qeema_ml.matching.lexical import LexicalIndex
from qeema_ml.matching.matcher import CatalogueIndexes, HybridMatcher, MatcherConfig
from qeema_ml.matching.normalise import normalise


@dataclass(frozen=True, slots=True)
class LabelledQuery:
    text: str
    expected_item_id: int
    perturbation: str


@dataclass
class EvaluationReport:
    n_queries: int
    top1_accuracy: float
    top3_accuracy: float
    top5_accuracy: float
    mean_reciprocal_rank: float
    auto_resolve_rate: float
    auto_resolve_precision: float
    review_rate: float
    reject_rate: float
    by_perturbation: dict[str, float]
    caveat: str

    def to_markdown(self) -> str:
        lines = [
            "# Product matching evaluation",
            "",
            f"Queries: **{self.n_queries}**",
            "",
            "| Metric | Value |",
            "|---|---|",
            f"| Top-1 accuracy | {self.top1_accuracy:.1%} |",
            f"| Top-3 accuracy | {self.top3_accuracy:.1%} |",
            f"| Top-5 accuracy | {self.top5_accuracy:.1%} |",
            f"| Mean reciprocal rank | {self.mean_reciprocal_rank:.3f} |",
            "",
            "## Routing",
            "",
            "| Outcome | Share | Precision |",
            "|---|---|---|",
            f"| Auto-resolved | {self.auto_resolve_rate:.1%} | {self.auto_resolve_precision:.1%} |",
            f"| Sent to review | {self.review_rate:.1%} | — |",
            f"| Rejected | {self.reject_rate:.1%} | — |",
            "",
            "Auto-resolve precision is the number that matters most: it is the share",
            "of matches the system accepted *without a human* that were correct.",
            "Everything routed to review is a cost, not an error.",
            "",
            "## Accuracy by perturbation",
            "",
            "| Perturbation | Top-1 accuracy |",
            "|---|---|",
        ]

        for name, accuracy in sorted(self.by_perturbation.items(), key=lambda kv: kv[1]):
            lines.append(f"| {name} | {accuracy:.1%} |")

        lines += ["", "## Caveat", "", self.caveat, ""]

        return "\n".join(lines)


def build_labelled_set(
    catalogue: list[dict],
    seed: int = 20260101,
) -> list[LabelledQuery]:
    """Generate labelled queries by perturbing known variants.

    Each perturbation mirrors a mistake real reporters make. The exact-match
    case is deliberately *excluded*: it is trivially correct by construction and
    including it would inflate every headline number.
    """
    rng = random.Random(seed)
    queries: list[LabelledQuery] = []

    for item in catalogue:
        item_id = int(item["canonical_item_id"])
        variants = [str(v) for v in item["variants"]]

        for variant in variants:
            normalised = normalise(variant)

            if not normalised:
                continue

            # Perturbations that normalisation fully absorbs are labelled as
            # such rather than being silently credited to whichever category
            # happened to be generated first. Dropping a hamza and writing
            # Arabic-Indic digits both normalise back to the canonical form —
            # that is exactly what the normaliser is for — so measuring them as
            # if they were distinct challenges would overstate the matcher's
            # robustness with queries it never actually had to work for.
            for perturbed, label in (
                (_drop_hamza(variant), "hamza_dropped"),
                (_arabic_digits(variant), "arabic_indic_digits"),
            ):
                changed = normalise(perturbed) != normalised
                queries.append(
                    LabelledQuery(
                        perturbed,
                        item_id,
                        label if changed else "absorbed_by_normalisation",
                    )
                )

            typo = _typo(normalised, rng)
            if typo != normalised:
                queries.append(LabelledQuery(typo, item_id, "typo"))

            tokens = normalised.split(" ")
            if len(tokens) > 1:
                queries.append(LabelledQuery(tokens[0], item_id, "head_noun_only"))
                queries.append(
                    LabelledQuery(" ".join(reversed(tokens)), item_id, "reordered_tokens")
                )

    # Deduplicate: several variants of one item perturb to the same string, and
    # counting that string twice would weight those items more heavily.
    seen: set[tuple[str, int]] = set()
    unique: list[LabelledQuery] = []

    for query in queries:
        key = (normalise(query.text), query.expected_item_id)

        if key in seen or not key[0]:
            continue

        seen.add(key)
        unique.append(query)

    return unique


def _drop_hamza(text: str) -> str:
    return text.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")


def _arabic_digits(text: str) -> str:
    return text.translate({ord(str(i)): chr(0x0660 + i) for i in range(10)})


def _typo(text: str, rng: random.Random) -> str:
    if len(text) < 5:
        return text

    i = rng.randint(1, len(text) - 2)

    return text[:i] + text[i + 1 :]


def evaluate(
    catalogue: list[dict],
    queries: list[LabelledQuery],
    config: MatcherConfig | None = None,
) -> EvaluationReport:
    rows = [
        {
            "canonical_item_id": item["canonical_item_id"],
            "canonical_item_code": item["canonical_item_code"],
            "text": variant,
            "normalized_text": normalise(variant),
        }
        for item in catalogue
        for variant in item["variants"]
    ]

    exact = {
        normalise(variant): (int(item["canonical_item_id"]), str(item["canonical_item_code"]))
        for item in catalogue
        for variant in item["variants"]
        if normalise(variant)
    }

    indexes = CatalogueIndexes(lexical=LexicalIndex.from_rows(rows), semantic=None, exact=exact)
    matcher = HybridMatcher(config or MatcherConfig(), embedder=None)

    hits = {1: 0, 3: 0, 5: 0}
    reciprocal_ranks: list[float] = []
    actions = {"auto_resolve": 0, "review": 0, "reject": 0}
    auto_correct = 0
    per_perturbation: dict[str, list[bool]] = {}

    for query in queries:
        decision = matcher.match(query.text, indexes)
        ranked = [c.canonical_item_id for c in decision.candidates]

        rank = (
            ranked.index(query.expected_item_id) + 1 if query.expected_item_id in ranked else None
        )

        for k in (1, 3, 5):
            if rank is not None and rank <= k:
                hits[k] += 1

        reciprocal_ranks.append(1.0 / rank if rank else 0.0)

        actions[decision.action] = actions.get(decision.action, 0) + 1

        if decision.action == "auto_resolve" and rank == 1:
            auto_correct += 1

        per_perturbation.setdefault(query.perturbation, []).append(rank == 1)

    n = max(1, len(queries))
    auto = max(1, actions["auto_resolve"])

    return EvaluationReport(
        n_queries=len(queries),
        top1_accuracy=hits[1] / n,
        top3_accuracy=hits[3] / n,
        top5_accuracy=hits[5] / n,
        mean_reciprocal_rank=sum(reciprocal_ranks) / n,
        auto_resolve_rate=actions["auto_resolve"] / n,
        auto_resolve_precision=auto_correct / auto,
        review_rate=actions["review"] / n,
        reject_rate=actions["reject"] / n,
        by_perturbation={
            name: sum(results) / len(results) for name, results in per_perturbation.items()
        },
        caveat=(
            "These figures are measured on **synthetically perturbed catalogue variants**, "
            "not on real reporter submissions. They characterise robustness to known "
            "classes of noise (dropped hamza, Arabic-Indic digits, typos, head-noun "
            "queries, token reordering) and should be read as an upper bound: real "
            "submissions contain dialect, brand names and item descriptions this set "
            "does not model. Replace with held-out human-reviewed decisions once enough "
            "have accumulated."
        ),
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluate product matching accuracy.")
    parser.add_argument("--catalogue", type=Path, required=True, help="JSON catalogue export")
    parser.add_argument("--out-json", type=Path, default=Path("artifacts/matching-eval.json"))
    parser.add_argument("--out-markdown", type=Path, default=Path("artifacts/matching-eval.md"))
    parser.add_argument("--seed", type=int, default=20260101)
    parser.add_argument(
        "--min-top1",
        type=float,
        default=0.0,
        help="Fail if top-1 accuracy falls below this, for use as a CI gate.",
    )

    args = parser.parse_args(argv)

    with args.catalogue.open(encoding="utf-8") as handle:
        catalogue = json.load(handle)

    queries = build_labelled_set(catalogue, seed=args.seed)
    report = evaluate(catalogue, queries)

    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(json.dumps(asdict(report), indent=2, ensure_ascii=False), "utf-8")
    args.out_markdown.write_text(report.to_markdown(), "utf-8")

    print(report.to_markdown())

    if report.top1_accuracy < args.min_top1:
        print(
            f"\nFAIL: top-1 accuracy {report.top1_accuracy:.1%} below required {args.min_top1:.1%}",
            file=sys.stderr,
        )

        return 1

    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
